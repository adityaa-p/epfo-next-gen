  translationsByLanguage[locale][value] || `${prefixes[locale]} · ${value}`;
export const translations = {
  en,
  ...Object.fromEntries(
    Object.keys(prefixes).map((locale) => [
      locale,
      Object.fromEntries(
        Object.entries(en).map(([key, value]) => [
          key,
          localize(locale, value),
        ]),
      ),
    ]),
  ),
};
export default translations;
